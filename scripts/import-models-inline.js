#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

function usage() {
  console.log('Usage: node scripts/import-models-inline.js <source-folder>');
  console.log('Example: node scripts/import-models-inline.js "C:/datasets/fruit-glb"');
}

const src = process.argv[2];
if (!src) {
  usage();
  process.exit(1);
}

const absSrc = path.resolve(process.cwd(), src);
if (!fs.existsSync(absSrc) || !fs.statSync(absSrc).isDirectory()) {
  console.error('Source folder not found or not a directory:', absSrc);
  process.exit(2);
}

const assetsDir = path.resolve(process.cwd(), 'src', 'assets', 'models');
fs.mkdirSync(assetsDir, { recursive: true });

const files = fs.readdirSync(absSrc).filter(f => /\.(glb|gltf)$/i.test(f));
if (files.length === 0) {
  console.log('No .glb/.gltf files found in', absSrc);
  process.exit(0);
}

const copied = [];
files.forEach((f) => {
  const srcPath = path.join(absSrc, f);
  const destName = f.replace(/\s+/g, '_');
  const destPath = path.join(assetsDir, destName);
  fs.copyFileSync(srcPath, destPath);
  copied.push(destName);
});

// Build `src/data/fruits.inline.js` with static imports using ?url
const imports = [];
const entries = {};

copied.forEach((name, idx) => {
  const varName = `m${idx}`;
  imports.push(`import ${varName} from '../assets/models/${name}?url';`);
  const base = name.replace(/\.[^.]+$/, '');
  if (/_sliced$/i.test(base)) {
    const root = base.replace(/_sliced$/i, '');
    entries[root] = entries[root] || {};
    entries[root].sliced = varName;
  } else {
    entries[base] = entries[base] || {};
    entries[base].whole = varName;
  }
});

const fruitsArr = Object.keys(entries).map((key) => {
  const e = entries[key];
  return {
    id: key.toLowerCase(),
    name: key.replace(/[-_]/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
    modelVar: e.whole || null,
    slicedVar: e.sliced || null
  };
});

const outPath = path.resolve(process.cwd(), 'src', 'data', 'fruits.inline.js');
let fileContents = `// Auto-generated by scripts/import-models-inline.js\n`;
fileContents += imports.join('\n') + '\n\n';
fileContents += `const fruits = [\n`;
fruitsArr.forEach((f) => {
  const modelExpr = f.modelVar ? f.modelVar : 'null';
  const slicedExpr = f.slicedVar ? f.slicedVar : 'null';
  fileContents += `  { id: '${f.id}', name: '${f.name}', modelPath: ${modelExpr}, slicedModelPath: ${slicedExpr} },\n`;
});
fileContents += `];\n\nexport default fruits;\n`;

fs.writeFileSync(outPath, fileContents, 'utf8');

console.log('Copied', copied.length, 'files to src/assets/models');
console.log('Generated', outPath);
console.log('Entries:', fruitsArr.length);
