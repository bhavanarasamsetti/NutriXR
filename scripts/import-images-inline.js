#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

function usage() {
  console.log('Usage: node scripts/import-images-inline.js <source-folder>');
  console.log('Example: node scripts/import-images-inline.js "C:/datasets/fruits_images"');
}

const src = process.argv[2];
if (!src) {
  usage();
  process.exit(1);
}

const absSrc = path.resolve(process.cwd(), src);
if (!fs.existsSync(absSrc) || !fs.statSync(absSrc).isDirectory()) {
  console.error('Source folder not found or not a directory:', absSrc);
  process.exit(2);
}

const assetsDir = path.resolve(process.cwd(), 'src', 'assets', 'images');
fs.mkdirSync(assetsDir, { recursive: true });

// accept common image extensions
const files = fs.readdirSync(absSrc).filter(f => /\.(jpg|jpeg|png|webp|bmp)$/i.test(f));
if (files.length === 0) {
  console.log('No image files found in', absSrc);
  process.exit(0);
}

const copied = [];
files.forEach((f) => {
  const srcPath = path.join(absSrc, f);
  const destName = f.replace(/\s+/g, '_');
  const destPath = path.join(assetsDir, destName);
  fs.copyFileSync(srcPath, destPath);
  copied.push(destName);
});

// Build `src/data/fruits.images.js` that imports images with ?url
const imports = [];
const entries = {}; // group by filename base; user can rename to indicate fruit

copied.forEach((name, idx) => {
  const varName = `i${idx}`;
  imports.push(`import ${varName} from '../assets/images/${name}?url';`);
  const base = name.replace(/\.[^.]+$/, '');
  const key = base.toLowerCase();
  // naive grouping: use filename base as fruit id
  entries[key] = entries[key] || {};
  // mark image field
  entries[key].image = varName;
});

const fruitsArr = Object.keys(entries).map((key) => {
  const e = entries[key];
  return {
    id: key.replace(/[^a-z0-9]+/g, '_'),
    name: key.replace(/[-_]/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
    imageVar: e.image
  };
});

const outPath = path.resolve(process.cwd(), 'src', 'data', 'fruits.images.js');
let fileContents = `// Auto-generated by scripts/import-images-inline.js\n`;
fileContents += imports.join('\n') + '\n\n';
fileContents += `const fruits = [\n`;
fruitsArr.forEach((f) => {
  const imageExpr = f.imageVar ? f.imageVar : 'null';
  fileContents += `  { id: '${f.id}', name: '${f.name}', modelPath: null, slicedModelPath: null, imagePath: ${imageExpr} },\n`;
});
fileContents += `];\n\nexport default fruits;\n`;

fs.writeFileSync(outPath, fileContents, 'utf8');

console.log('Copied', copied.length, 'images to src/assets/images');
console.log('Generated', outPath);
console.log('Entries:', fruitsArr.length);
